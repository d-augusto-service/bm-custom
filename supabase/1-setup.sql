-- Dados de pagamento para o site (respeita "mostrarDados")
create or replace function public.pagamento_publico() returns jsonb
language sql stable security definer set search_path = public as $$
  select case
           when coalesce((dados->>'mostrarDados')::boolean, true) then dados
           else jsonb_build_object('mostrarDados', false)
         end
  from public.pagamento where id = 1;
$$;

-- Cria a encomenda: o PREÇO e o STOCK são sempre decididos aqui, nunca pelo navegador.
create or replace function public.criar_encomenda(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_def    jsonb;
  v_nome   text; v_tel text; v_zona text; v_end text; v_obs text; v_metodo text;
  v_taxa   integer;
  v_sub    integer := 0;
  v_id     bigint;
  v_cod    text;
  v_n      integer;
  v_cnt    integer := 0;
  v_dist   integer;
  v_itens  jsonb := '[]'::jsonb;
  v_lin    jsonb;
  r        record;
  v_alfa   constant text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
begin
  select dados into v_def from public.definicoes where id = 1;
  if v_def is null then raise exception 'A loja não está disponível de momento.'; end if;

  v_nome   := btrim(coalesce(p->>'nome', ''));
  v_tel    := regexp_replace(coalesce(p->>'telefone', ''), '[\s-]', '', 'g');
  v_zona   := btrim(coalesce(p->>'zona', ''));
  v_end    := btrim(coalesce(p->>'endereco', ''));
  v_obs    := left(btrim(coalesce(p->>'obs', '')), 500);
  v_metodo := coalesce(p->>'metodo', '');

  if char_length(v_nome) not between 2 and 100 then raise exception 'Indique o seu nome.'; end if;
  if v_tel !~ '^\+?[0-9]{9,15}$' then raise exception 'Número de telefone inválido.'; end if;
  if not coalesce((v_def->'zonas') ? v_zona, false) then raise exception 'Escolha uma zona de entrega válida.'; end if;
  if char_length(v_end) not between 5 and 300 then raise exception 'Indique o endereço ou uma referência de localização.'; end if;
  if v_metodo not in ('multicaixa', 'paypay', 'iban') then raise exception 'Escolha um método de pagamento.'; end if;

  if jsonb_typeof(p->'itens') is distinct from 'array'
     or jsonb_array_length(p->'itens') not between 1 and 50 then
    raise exception 'O carrinho está vazio ou é inválido.';
  end if;
  for v_lin in select * from jsonb_array_elements(p->'itens') loop
    if (v_lin->>'v') is null or (v_lin->>'v') !~ '^[0-9]{1,15}$'
       or (v_lin->>'q') is null or (v_lin->>'q') !~ '^[1-9][0-9]?$' then
      raise exception 'Item inválido no carrinho.';
    end if;
  end loop;

  -- Limite simples contra abuso: no máximo 3 encomendas por confirmar, por telefone, na última hora
  select count(*) into v_n from public.encomendas
   where telefone = v_tel and estado = 'nova' and estado_pagamento = 'pendente'
     and criado_em > now() - interval '1 hour';
  if v_n >= 3 then
    raise exception 'Já tem encomendas por confirmar. Fale connosco pelo WhatsApp.';
  end if;

  v_taxa := case when coalesce(v_def->>'taxa_entrega', '') ~ '^[0-9]{1,9}$'
                 then (v_def->>'taxa_entrega')::integer else 0 end;

  select count(distinct (e->>'v')::bigint) into v_dist from jsonb_array_elements(p->'itens') e;

  -- Reserva o stock (linhas bloqueadas por ordem de id, para evitar bloqueios cruzados)
  for r in
    select x.q, vr.id, vr.tamanho, vr.cor, vr.stock, pr.nome, pr.preco, pr.preco_promo, pr.publicado
      from (select (e->>'v')::bigint as vid, sum((e->>'q')::integer)::integer as q
              from jsonb_array_elements(p->'itens') e group by 1) x
      join public.variantes vr on vr.id = x.vid
      join public.produtos  pr on pr.id = vr.produto_id
     order by vr.id
       for update of vr
  loop
    v_cnt := v_cnt + 1;
    if not r.publicado or coalesce(r.preco_promo, r.preco) < 1 then
      raise exception 'Produto indisponível: %.', r.nome;
    end if;
    if r.q > 99 then raise exception 'Quantidade inválida.'; end if;
    if r.stock < r.q then
      raise exception 'Sem stock suficiente: % (%, %). Restam %.', r.nome, r.tamanho, r.cor, r.stock;
    end if;
    update public.variantes set stock = stock - r.q where id = r.id;
    v_sub := v_sub + coalesce(r.preco_promo, r.preco) * r.q;
    v_itens := v_itens || jsonb_build_array(jsonb_build_object(
      'v', r.id, 'nome', r.nome, 'tamanho', r.tamanho, 'cor', r.cor,
      'q', r.q, 'preco', coalesce(r.preco_promo, r.preco)));
  end loop;
  if v_cnt = 0 or v_cnt <> v_dist then raise exception 'Algum produto do carrinho já não está disponível.'; end if;

  loop
    select 'BM-' || string_agg(substr(v_alfa, 1 + floor(random() * length(v_alfa))::integer, 1), '')
      into v_cod from generate_series(1, 6);
    exit when not exists (select 1 from public.encomendas where codigo = v_cod);
  end loop;

  insert into public.encomendas(codigo, nome, telefone, zona, endereco, obs, metodo, subtotal, entrega, total)
  values (v_cod, v_nome, v_tel, v_zona, v_end, v_obs, v_metodo, v_sub, v_taxa, v_sub + v_taxa)
  returning id into v_id;

  insert into public.itens(encomenda_id, variante_id, nome, tamanho, cor, preco_unit, qtd)
  select v_id, (e->>'v')::bigint, e->>'nome', e->>'tamanho', e->>'cor', (e->>'preco')::integer, (e->>'q')::integer
    from jsonb_array_elements(v_itens) e;

  insert into public.historico(encomenda_id, evento) values (v_id, 'Encomenda criada; pagamento pendente');

  return jsonb_build_object(
    'codigo', v_cod, 'subtotal', v_sub, 'entrega', v_taxa, 'total', v_sub + v_taxa,
    'itens', (select jsonb_agg(jsonb_build_object('nome', e->>'nome', 'tamanho', e->>'tamanho', 'cor', e->>'cor',
                                                  'q', (e->>'q')::integer, 'preco', (e->>'preco')::integer))
                from jsonb_array_elements(v_itens) e));
end;
$$;

-- Administrador: muda o estado de uma encomenda e/ou marca o pagamento como recebido
create or replace function public.admin_atualizar_encomenda(p_id bigint, p_estado text default null, p_pagamento text default null)
returns void language plpgsql security definer set search_path = public as $$
declare e record;
begin
  if not public.is_admin() then raise exception 'Sem permissão.' using errcode = '42501'; end if;
  select * into e from public.encomendas where id = p_id for update;
  if not found then raise exception 'Encomenda inexistente.'; end if;

  if p_estado is not null and p_estado <> e.estado then
    if p_estado not in ('nova','em preparação','em entrega','entregue','cancelada') then
      raise exception 'Estado inválido.';
    end if;
    if e.estado = 'cancelada' then raise exception 'Uma encomenda cancelada não pode ser reaberta.'; end if;
    if p_estado = 'cancelada' then   -- o stock volta
      update public.variantes v set stock = v.stock + i.qtd
        from public.itens i where i.encomenda_id = p_id and v.id = i.variante_id;
    end if;
    update public.encomendas set estado = p_estado where id = p_id;
    insert into public.historico(encomenda_id, evento)
    values (p_id, 'Estado: ' || p_estado || case when p_estado = 'cancelada' then ' (stock devolvido)' else '' end);
  end if;

  if p_pagamento = 'pago' and e.estado_pagamento <> 'pago' then
    update public.encomendas set estado_pagamento = 'pago' where id = p_id;
    insert into public.historico(encomenda_id, evento) values (p_id, 'Pagamento confirmado pelo administrador');
  end if;
end;
$$;

-- Administrador: cria ou altera um produto e o stock de todas as variantes (tudo ou nada)
create or replace function public.admin_guardar_produto(p jsonb) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v_id    bigint := nullif(p->>'id', '')::bigint;
  v_nome  text   := btrim(coalesce(p->>'nome', ''));
  v_cat   text   := coalesce(p->>'categoria', '');
  v_preco integer;
  v_promo integer;
  v_pub   boolean := coalesce((p->>'publicado')::boolean, false);
  v_slug  text; v_base text; v_i integer := 1;
  v_var   jsonb;
begin
  if not public.is_admin() then raise exception 'Sem permissão.' using errcode = '42501'; end if;
  if char_length(v_nome) not between 2 and 120 then raise exception 'Indique o nome do produto.'; end if;
  if v_cat not in ('virgens','personalizadas','marca-propria') then raise exception 'Categoria inválida.'; end if;

  if coalesce(p->>'preco', '0') !~ '^[0-9]{1,9}$' then raise exception 'Preço inválido.'; end if;
  v_preco := coalesce(p->>'preco', '0')::integer;
  if coalesce(p->>'preco_promo', '') <> '' then
    if (p->>'preco_promo') !~ '^[0-9]{1,9}$' then raise exception 'Preço promocional inválido.'; end if;
    v_promo := (p->>'preco_promo')::integer;
    if v_promo >= v_preco then raise exception 'O preço promocional tem de ser inferior ao preço.'; end if;
  end if;
  if v_pub and v_preco < 1 then raise exception 'Defina o preço antes de publicar.'; end if;

  if jsonb_typeof(coalesce(p->'imagens', '[]'::jsonb)) <> 'array' or jsonb_array_length(coalesce(p->'imagens', '[]'::jsonb)) > 10 then
    raise exception 'Fotografias inválidas (máximo 10).';
  end if;
  if exists (select 1 from jsonb_array_elements_text(coalesce(p->'imagens', '[]'::jsonb)) u
              where u !~ '^(https://|assets/)[^[:space:]"''<>]+$' or char_length(u) > 500) then
    raise exception 'Endereço de fotografia inválido.';
  end if;

  if jsonb_typeof(coalesce(p->'variantes', '[]'::jsonb)) <> 'array' then raise exception 'Variantes inválidas.'; end if;
  for v_var in select * from jsonb_array_elements(coalesce(p->'variantes', '[]'::jsonb)) loop
    if char_length(btrim(coalesce(v_var->>'tamanho', ''))) not between 1 and 20
       or char_length(btrim(coalesce(v_var->>'cor', ''))) not between 1 and 40
       or coalesce(v_var->>'stock', '') !~ '^[0-9]{1,6}$' then
      raise exception 'Tamanho, cor ou stock inválidos.';
    end if;
  end loop;

  if v_id is null then
    v_base := coalesce(nullif(p->>'slug', ''), 'produto');
    if v_base !~ '^[a-z0-9]+(-[a-z0-9]+)*$' then v_base := 'produto'; end if;
    v_slug := v_base;
    while exists (select 1 from public.produtos where slug = v_slug) loop
      v_i := v_i + 1; v_slug := v_base || '-' || v_i;
    end loop;
    insert into public.produtos(slug, nome, categoria, descricao, preco, preco_promo, imagens, publicado, destaque, novo)
    values (v_slug, v_nome, v_cat, left(coalesce(p->>'descricao', ''), 2000), v_preco, v_promo,
            coalesce(p->'imagens', '[]'::jsonb), v_pub,
            coalesce((p->>'destaque')::boolean, false), coalesce((p->>'novo')::boolean, false))
    returning id into v_id;
  else
    update public.produtos set nome = v_nome, categoria = v_cat, descricao = left(coalesce(p->>'descricao', ''), 2000),
           preco = v_preco, preco_promo = v_promo, imagens = coalesce(p->'imagens', '[]'::jsonb),
           publicado = v_pub, destaque = coalesce((p->>'destaque')::boolean, false), novo = coalesce((p->>'novo')::boolean, false)
     where id = v_id;
    if not found then raise exception 'Produto inexistente.'; end if;
  end if;

  -- variantes: as que vêm na lista ficam (com o stock indicado); as que não vêm são removidas
  delete from public.variantes vr
   where vr.produto_id = v_id
     and not exists (select 1 from jsonb_array_elements(coalesce(p->'variantes', '[]'::jsonb)) e
                      where btrim(e->>'tamanho') = vr.tamanho and btrim(e->>'cor') = vr.cor);
  insert into public.variantes(produto_id, tamanho, cor, stock)
  select v_id, btrim(e->>'tamanho'), btrim(e->>'cor'), (e->>'stock')::integer
    from jsonb_array_elements(coalesce(p->'variantes', '[]'::jsonb)) e
  on conflict (produto_id, tamanho, cor) do update set stock = excluded.stock;

  return v_id;
end;
$$;

