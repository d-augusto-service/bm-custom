-- ---------- 1. Administradores -----------------------------------------
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.admins enable row level security;
drop policy if exists "admin vê a própria linha" on public.admins;
create policy "admin vê a própria linha" on public.admins
  for select to authenticated using (user_id = (select auth.uid()));

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

-- ---------- 2. Tabelas --------------------------------------------------
create table if not exists public.produtos (
  id          bigint generated by default as identity primary key,
  slug        text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  nome        text not null check (char_length(nome) between 2 and 120),
  categoria   text not null check (categoria in ('virgens','personalizadas','marca-propria')),
  descricao   text not null default '' check (char_length(descricao) <= 2000),
  preco       integer not null default 0 check (preco >= 0),
  preco_promo integer check (preco_promo is null or preco_promo >= 0),
  imagens     jsonb not null default '[]'::jsonb check (jsonb_typeof(imagens) = 'array'),
  publicado   boolean not null default false,
  destaque    boolean not null default false,
  novo        boolean not null default false,
  criado_em   timestamptz not null default now(),
  check (preco_promo is null or preco_promo < preco),
  check (not publicado or preco > 0)
);

create table if not exists public.variantes (
  id         bigint generated by default as identity primary key,
  produto_id bigint not null references public.produtos(id) on delete cascade,
  tamanho    text not null check (char_length(tamanho) between 1 and 20),
  cor        text not null check (char_length(cor) between 1 and 40),
  stock      integer not null default 0 check (stock >= 0),
  unique (produto_id, tamanho, cor)
);

create table if not exists public.encomendas (
  id               bigint generated by default as identity primary key,
  codigo           text not null unique,
  nome             text not null,
  telefone         text not null,
  zona             text not null,
  endereco         text not null,
  obs              text not null default '',
  metodo           text not null,
  subtotal         integer not null,
  entrega          integer not null,
  total            integer not null,
  estado           text not null default 'nova'
                   check (estado in ('nova','em preparação','em entrega','entregue','cancelada')),
  estado_pagamento text not null default 'pendente' check (estado_pagamento in ('pendente','pago')),
  criado_em        timestamptz not null default now()
);

create table if not exists public.itens (
  id           bigint generated by default as identity primary key,
  encomenda_id bigint not null references public.encomendas(id) on delete cascade,
  variante_id  bigint,                       -- sem chave estrangeira: o histórico fica mesmo que a variante seja apagada
  nome         text not null,
  tamanho      text not null,
  cor          text not null,
  preco_unit   integer not null,
  qtd          integer not null check (qtd > 0)
);

create table if not exists public.historico (
  id           bigint generated by default as identity primary key,
  encomenda_id bigint not null references public.encomendas(id) on delete cascade,
  evento       text not null,
  criado_em    timestamptz not null default now()
);

-- Definições públicas (entrega, zonas, WhatsApp, banner, tamanhos, cores)
create table if not exists public.definicoes (
  id    integer primary key check (id = 1),
  dados jsonb not null
);
-- Dados de pagamento (só o administrador lê a tabela; o público recebe-os pela função pagamento_publico)
create table if not exists public.pagamento (
  id    integer primary key check (id = 1),
  dados jsonb not null
);

create index if not exists variantes_produto_idx on public.variantes(produto_id);
create index if not exists itens_encomenda_idx   on public.itens(encomenda_id);
create index if not exists hist_encomenda_idx    on public.historico(encomenda_id);
create index if not exists enc_criado_idx        on public.encomendas(criado_em desc);
create index if not exists enc_tel_idx           on public.encomendas(telefone, criado_em desc);

