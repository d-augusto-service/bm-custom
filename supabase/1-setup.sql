-- Produtos e variantes: o público só vê os publicados; o administrador vê e altera tudo
drop policy if exists produtos_ler  on public.produtos;
drop policy if exists produtos_admin on public.produtos;
create policy produtos_ler   on public.produtos for select to anon, authenticated
  using (publicado or (select public.is_admin()));
create policy produtos_admin on public.produtos for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists variantes_ler  on public.variantes;
drop policy if exists variantes_admin on public.variantes;
create policy variantes_ler  on public.variantes for select to anon, authenticated
  using ((select public.is_admin())
         or exists (select 1 from public.produtos p where p.id = produto_id and p.publicado));
create policy variantes_admin on public.variantes for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

-- Definições: leitura pública, escrita só do administrador
drop policy if exists definicoes_ler   on public.definicoes;
drop policy if exists definicoes_admin on public.definicoes;
create policy definicoes_ler   on public.definicoes for select to anon, authenticated using (true);
create policy definicoes_admin on public.definicoes for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

-- Pagamento: só o administrador
drop policy if exists pagamento_admin on public.pagamento;
create policy pagamento_admin on public.pagamento for all to authenticated
  using ((select public.is_admin())) with check ((select public.is_admin()));

-- Encomendas, itens e histórico: só o administrador lê; ninguém escreve diretamente
-- (as encomendas entram pela função criar_encomenda e mudam pela função admin_atualizar_encomenda)
drop policy if exists enc_admin  on public.encomendas;
drop policy if exists itens_admin on public.itens;
drop policy if exists hist_admin on public.historico;
create policy enc_admin   on public.encomendas for select to authenticated using ((select public.is_admin()));
create policy itens_admin on public.itens      for select to authenticated using ((select public.is_admin()));
create policy hist_admin  on public.historico  for select to authenticated using ((select public.is_admin()));

revoke all on public.encomendas, public.itens, public.historico, public.admins, public.pagamento from anon;
revoke insert, update, delete on public.encomendas, public.itens, public.historico from authenticated;

